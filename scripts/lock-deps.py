#!/usr/bin/env python3
"""Write a requirements lock (exact pins + sha256 hashes) from its input file.

    PY_NET=bridge scripts/py.sh 'python scripts/lock-deps.py 2026-10-24 requirements.in' > requirements.txt
    PY_NET=bridge scripts/py.sh 'python scripts/lock-deps.py 2026-10-24 requirements-dev.in' > requirements-dev.txt

Standard library only. For every pin it asks the PyPI JSON API for the files of that exact release and keeps the
wheels that matter here: pure Python wheels and CPython 3.12/3.13 wheels for Linux x86_64 and aarch64. It fails
when a pin has no usable wheel for one of those targets, is yanked, or has a kept file uploaded after the cutoff
(the dependency age policy: at least seven days old). Hashes are the ones PyPI publishes; pip verifies them with
--require-hashes.
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

TARGETS = [("cp312", "x86_64"), ("cp312", "aarch64"), ("cp313", "x86_64"), ("cp313", "aarch64")]
WHEEL = re.compile(
    r"^(?P<name>[^-]+)-(?P<ver>[^-]+)(-(?P<build>\d[^-]*))?-(?P<py>[^-]+)-(?P<abi>[^-]+)-(?P<plat>[^-]+)\.whl$"
)


def fetch(name: str, version: str) -> dict[str, object]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        data: dict[str, object] = json.load(response)
    return data


def covers(wheel: str, interpreter: str, arch: str) -> bool:
    m = WHEEL.match(wheel)
    if m is None:
        return False
    py, abi, plat = m["py"].split("."), m["abi"].split("."), m["plat"].split(".")
    if "any" not in plat and not any(p.endswith(arch) and ("manylinux" in p or "musllinux" in p) for p in plat):
        return False
    if "none" in abi:  # pure Python, or a binary that does not link to the interpreter (a command line tool)
        return any(p.startswith("py3") for p in py)
    if interpreter in abi:
        return interpreter in py
    # stable ABI wheel built for this interpreter or an older one
    target = int(interpreter[3:])
    return "abi3" in abi and any(re.fullmatch(r"cp3\d+", p) is not None and int(p[3:]) <= target for p in py)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: lock-deps.py CUTOFF INPUT_FILE > LOCK_FILE", file=sys.stderr)
        return 2
    cutoff = datetime.fromisoformat(sys.argv[1]).replace(tzinfo=UTC)
    lines: list[str] = []
    problems: list[str] = []
    for line in Path(sys.argv[2]).read_text().splitlines():
        raw = line.strip()
        if not raw or raw.startswith("#"):
            continue
        name, _, version = raw.partition("==")
        release = fetch(name, version)
        files = release["urls"]
        assert isinstance(files, list)
        kept = [f for f in files if f["packagetype"] == "bdist_wheel" and not f["yanked"]]
        for interpreter, arch in TARGETS:
            if not any(covers(f["filename"], interpreter, arch) for f in kept):
                problems.append(f"{name}=={version}: no wheel for {interpreter} {arch}")
        kept = [f for f in kept if any(covers(f["filename"], i, a) for i, a in TARGETS)]
        for f in kept:
            uploaded = datetime.fromisoformat(f["upload_time_iso_8601"].replace("Z", "+00:00"))
            if uploaded > cutoff:
                problems.append(f"{f['filename']}: uploaded {uploaded.isoformat()} after the cutoff")
        hashes = sorted({f["digests"]["sha256"] for f in kept})
        lines.append(f"{name}=={version} \\")
        lines.extend(f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes))
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    print(f"# Generated by scripts/lock-deps.py from {Path(sys.argv[2]).name} (cutoff {cutoff.isoformat()}). Do not edit.")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
